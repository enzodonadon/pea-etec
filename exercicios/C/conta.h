#ifndef CONTA_H
#define CONTA_H


double soma(double num1, double num2){
    return num1 + num2;
}

double sub(double num1, double num2){
    return num1 - num2;
}

double mult(double num1, double num2){
    return num1 * num2;
}

double divisor(double num1, double num2){
    return num1 / num2;
}

#endif